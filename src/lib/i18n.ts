export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let text = translations[locale]?.[key] || translations.fr[key] || key
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v))
    })
  }
  return text
}

export function getMealPlanLabel(locale: Locale, plan: string): string {
  return t(locale, `mealPlan.${plan}`)
}

export function getRoleLabel(locale: Locale, role: string): string {
  return t(locale, `role.${role}`)
}
